export function getCuratedStationsForCategory(categoryId = 'featured', query = '') {
  const q = (query || '').trim().toLowerCase();
  if (q) {
    return CURATED_WORLD_STATIONS.filter(
      (s) =>
        s.title.toLowerCase().includes(q) ||
        s.artist.toLowerCase().includes(q) ||
        s.genre.toLowerCase().includes(q) ||
        (s.country || '').toLowerCase().includes(q) ||
        (s.categories || []).some((c) => c.toLowerCase().includes(q))
    );
  }
  if (!categoryId || categoryId === 'featured') {
    return CURATED_WORLD_STATIONS.filter((s) => s.categories.includes('featured'));
  }
  return CURATED_WORLD_STATIONS.filter((s) => s.categories.includes(categoryId));
}
